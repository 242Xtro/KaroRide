    fun message(value: String): String {
        messages[value]?.let { return get(it) }
        return when {
            value.startsWith("Modellprüfung fehlgeschlagen: erwartet wird ") -> get(R.string.message_model_mismatch, value.removePrefix("Modellprüfung fehlgeschlagen: erwartet wird ").removeSuffix("."))
            value.startsWith("Kamera-SDK konnte nicht geladen werden. Gerätefähigkeiten prüfen (") -> get(R.string.message_sdk_load_failed, value.substringAfter("(").removeSuffix(")."))
            value.startsWith("Aufwecksignal fehlgeschlagen (") -> get(R.string.message_wake_failed, value.substringAfter("(").substringBefore(")"))
            value.startsWith("Bluetooth-Suche fehlgeschlagen (") || value.startsWith("Bluetooth scan failed (") -> get(R.string.scan_failed, value.substringAfter("(").substringBefore(")").toIntOrNull() ?: -1)
            else -> value // Unknown manufacturer diagnostics/codes remain verbatim.
        }
    }
